import re

def mask_pii(text: str) -> str:
    """
    사용자가 입력한 텍스트에서 개인식별정보(PII)를 감지하여 마스킹 처리합니다.
    - 주민등록번호 (예: 900101-1234567, 9001011234567)
    - 계좌번호 (3자리 이상 - 2자리 이상 - 3자리 이상 숫자 조합)
    - 휴대폰/전화번호 (예: 010-1234-5678, 02-123-4567)
    """
    if not text:
        return text

    # 1. 주민등록번호 패턴 (생년월일 6자리 + 성별/지역코드 7자리)
    # 하이픈(-) 유무 모두 대응
    rrn_pattern = r'\b\d{2}(0[1-9]|1[0-2])(0[1-9]|[12]\d|3[01])[-_?]?[1-4]\d{6}\b'
    text = re.sub(rrn_pattern, '[주민등록번호 마스킹됨]', text)

    # 2. 계좌번호 패턴 (은행별 다양한 하이픈 패턴 대응: ex. 110-123-456789)
    # 최소 3자-2자-3자 이상의 구조
    account_pattern = r'\b\d{3,6}[-]\d{2,6}[-]\d{3,6}\b'
    text = re.sub(account_pattern, '[계좌번호 마스킹됨]', text)

    # 3. 전화번호 패턴 (010, 02, 031 등)
    phone_pattern = r'\b(01[016789]|02|0[3-6][1-5])[-_.]?\d{3,4}[-_.]?\d{4}\b'
    text = re.sub(phone_pattern, '[전화번호 마스킹됨]', text)

    return text


# ==========================================
# 🧪 기능 테스트용 코드
# ==========================================
if __name__ == "__main__":
    sample_inputs = [
        "고객 주민번호가 950101-1234567 인데 암보험 가입 가능한가요?",
        "환급금 입금 계좌는 국민은행 123-456-789012 입니다.",
        "연락처 010-9876-5432 로 제안서 송부 바랍니다."
    ]

    print("=== 마스킹 전처리 테스트 ===")
    for sample in sample_inputs:
        masked = mask_pii(sample)
        print(f"원본: {sample}")
        print(f"마스킹: {masked}\n")